    /**
     * Called by TurnManagementWoZ when the VAD state changes.
     * Updates button states on the Swing EDT.
     */
    @Override
    public void onVadStateChanged(boolean userSpeaking, boolean agentSpeaking) {
        SwingUtilities.invokeLater(() -> {
            updateNodButtonsState(userSpeaking, agentSpeaking);
        });
    }

    /**
     * Enable or disable the nod buttons based on conditions.
     * Buttons are enabled only when user is speaking AND agent is NOT speaking.
     * 
     * Override this method if you add your own button references from the form editor.
     * For now, it searches for buttons by name in the component hierarchy.
     */
    private void updateNodButtonsState(boolean userSpeaking, boolean agentSpeaking) {
        boolean canSendNod = userSpeaking && !agentSpeaking;
        ShortNod.setEnabled(canSendNod);
        LongNod.setEnabled(canSendNod);
        NodTwice.setEnabled(canSendNod);
    }

